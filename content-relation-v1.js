  function flag(value, fallback) { return value == null ? fallback === true : value === true; }
  function resolveInput(input) {
    const source = input || {};
    const chart = source.chart || (source.pillars && source.astro ? source : null);
    const suppliedMoon = source.moon && typeof source.moon === 'object' ? source.moon : null;
    const astroMoon = chart && chart.astro && chart.astro.moon;
    const chartGod = godFromChart(chart);
    const explicitGod = text(source.relationGod);
    const relationGod = explicitGod || chartGod.name;
    const relationLabel = !explicitGod || explicitGod === chartGod.name ? chartGod.label : '关系十神';
    return {
      stem:text(source.stem || source.dayStem || (chart && chart.pillars && chart.pillars.day && chart.pillars.day.stem)),
      moonSign:normalizeMoonSign(source.moonSign || (suppliedMoon && suppliedMoon.sign) || (typeof source.moon === 'string' && source.moon) || (astroMoon && astroMoon.sign)),
      relationGod:relationGod, relationLabel:relationLabel,
      moonApprox:flag(source.moonApprox, flag(suppliedMoon && suppliedMoon.approx, astroMoon && astroMoon.approx)),
      moonNearEdge:flag(source.moonNearEdge, flag(suppliedMoon && suppliedMoon.nearEdge, astroMoon && astroMoon.nearEdge))
    };
  }

