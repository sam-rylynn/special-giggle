  function clone(value) { return JSON.parse(JSON.stringify(value)); }
  function text(value) { return String(value == null ? '' : value).trim(); }
  function signName(value) {
    const name = text(value && value.sign ? value.sign : value);
    return name ? (name.endsWith('座') ? name : name + '座') : '';
  }
  function shortSign(value) { return signName(value).replace(/座$/, ''); }
  function contextOf(value) {
    const supplied = value || {};
    const chart = supplied.chart || supplied;
    const astro = chart.astro || supplied.astro || {};
    const pillars = chart.pillars || {};
    const dayMaster = chart.dayMaster || {};
    return {
      stem:text(supplied.stem || supplied.dayStem || dayMaster.stem || (pillars.day && pillars.day.stem)),
      sun:signName(supplied.sun || supplied.sunSign || (astro.sun && astro.sun.sign)),
      asc:signName(supplied.asc || supplied.ascSign || (astro.asc && astro.asc.sign)),
      input:Object.assign({}, chart.input || {}, supplied.input || {})
    };
  }
  function requirePair(stem, sun) {
    if (!STEM[stem]) throw new TypeError('未知日主：' + (stem || '空'));
    if (!SUN[sun]) throw new TypeError('未知太阳星座：' + (sun || '空'));
  }
  function combinationKey(stem, sun) {
    const normalizedStem = text(stem);
    const normalizedSun = signName(sun);
    requirePair(normalizedStem, normalizedSun);
    return normalizedStem + '×' + normalizedSun;
  }
  function fusionTypeFor(stem, sun) {
    const key = combinationKey(stem, sun);
    if (DOUBLE_CONFIRM_PAIRS.has(key)) return '双重确认';
    if ((DELIBERATE_STEMS.has(stem) && FAST_PUBLIC_SIGNS.has(sun)) ||
        (FAST_STEMS.has(stem) && STEADY_PUBLIC_SIGNS.has(sun))) return '内外反差';
    if (RELATIONAL_PUBLIC_SIGNS.has(sun)) return '场景切换';
    return '反向补偿';
  }
  function buildPair(stem, sun) {
    const key = combinationKey(stem, sun);
    const day = STEM[stem];
    const solar = SUN[sun];
    const pair = PAIR_COPY[key];
    const label = stem + day.element;
    const type = fusionTypeFor(stem, sun);
    const source = '日主·' + label + '｜太阳·' + sun;
    return {
      key:key,
      home:{
        identity:label + ' × 太阳' + shortSign(sun),
        dayMaster:{label:label,image:day.image},
        fusionType:type,
        judgement:pair.judgement,
        explanation:label + '与太阳' + shortSign(sun) + '的双盘合成判断。',
        keywords:[day.keyword,solar.keyword,type],
        steps:[
          {title:day.title,body:day.home},
          {title:solar.title,body:solar.home},
          {title:pair.judgement.replace(/。$/, ''),body:pair.detail}
        ],
        firstImpression:'',
        drive:day.drive,
        scenes:[
          {title:'独处的时候',body:day.solo},
          {title:'和大家在一起时',body:solar.group}
        ],
        overuse:{title:pair.riskTitle,body:pair.risk,action:pair.advice},
        reportQuestions:[
          day.question,
          solar.question,
          '当前大运与流年，正在把哪些事情推到眼前？'
        ],
        source:source
      },
      reportOverview:{
        hero:day.reportTitle,
        title:'双盘合成判断',
        lead:'日主' + day.report,
        keywords:[day.keyword,solar.keyword,type],
        scenes:[
          {title:solar.hero,body:solar.report},
          {title:'双盘合成判断',body:pair.bridge}
        ],
        tension:'',
        source:source
      },
      dualShare:clone(LOCKED_SHARES[key])
    };
  }
  const COMBINATIONS = {};
  DAY_STEMS.forEach(function(stem) {
    SUN_SIGNS.forEach(function(sun) {
      const pair = buildPair(stem, sun);
      COMBINATIONS[pair.key] = pair;
    });
  });
  function getPair(stem, sun) {
    return clone(COMBINATIONS[combinationKey(stem, sun)]);
  }
  function buildHome(value) {
    const ctx = contextOf(value);
    const home = getPair(ctx.stem, ctx.sun).home;
    if (ctx.asc) {
      if (!ASC[ctx.asc]) throw new TypeError('未知上升星座：' + ctx.asc);
      home.firstImpression = ASC[ctx.asc];
    }
    return home;
  }
  function buildReportOverview(value) {
    const ctx = contextOf(value);
    return getPair(ctx.stem, ctx.sun).reportOverview;
  }
  function buildShare(value) {
    const ctx = contextOf(value);
    return clone(LOCKED_SHARES[combinationKey(ctx.stem, ctx.sun)]);
  }
  function buildContent(value) {
    const ctx = contextOf(value);
    return {
      key:combinationKey(ctx.stem, ctx.sun),
      home:buildHome(value),
      reportOverview:buildReportOverview(value),
      dualShare:buildShare(value)
    };
  }
  function inputNumber(input, longName, shortName) {
    return Number(input[longName] != null ? input[longName] : input[shortName]);
  }
  // 兼容旧调用方的样例识别；识别结果不控制文案选择。
  function isExactV2Sample(value) {
    const ctx = contextOf(value);
    const input = ctx.input || {};
    const city = text(input.city || input.c).replace(/市$/, '');
    const gender = text(input.gender || input.g).toUpperCase();
    return ctx.stem === '壬' && ctx.sun === '双子座' && ctx.asc === '巨蟹座'
      && inputNumber(input, 'year', 'y') === 1992
      && inputNumber(input, 'month', 'm') === 6
      && inputNumber(input, 'day', 'd') === 15
      && inputNumber(input, 'hour', 'hh') === 8
      && inputNumber(input, 'minute', 'mm') === 30
      && city === '贵阳'
      && (gender === '男' || gender === 'M' || gender === 'MALE');
  }
