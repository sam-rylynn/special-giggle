function sameNumber(value, expected) {
  return Number(value) === expected;
}

function isSampleInput(input) {
  if (!input) return false;
  const city = String(input.city || input.c || '').trim();
  const gender = String(input.gender || input.g || '').trim();
  return sameNumber(input.y, SAMPLE_INPUT.y)
    && sameNumber(input.m, SAMPLE_INPUT.m)
    && sameNumber(input.d, SAMPLE_INPUT.d)
    && sameNumber(input.hh, SAMPLE_INPUT.hh)
    && sameNumber(input.mm, SAMPLE_INPUT.mm)
    && city.replace(/市$/, '') === SAMPLE_INPUT.city
    && gender === SAMPLE_INPUT.gender;
}

function isSampleChart(chart) {
  if (!chart || !isSampleInput(chart.input)) return false;
  const p = chart.pillars || {};
  const sign = chart.astro || {};
  const pillar = key => p[key] ? `${p[key].stem}${p[key].branch}` : '';
  return pillar('year') === '壬申'
    && pillar('month') === '丙午'
    && pillar('day') === '壬戌'
    && pillar('hour') === '甲辰'
    && chart.fiveElements?.dayMasterStrength?.label === '偏弱'
    && sign.sun?.sign === '双子座'
    && sign.moon?.sign === '射手座'
    && sign.asc?.sign === '巨蟹座';
}

